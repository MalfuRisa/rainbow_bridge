import { test, expect } from '@playwright/test'
import { mockApi, scopeQuery, CSRF, fail, login, ok, identity } from './mock'

test('D-F03 JSON、上传、导入预览/写入与ZIP导出共用CSRF，不手填multipart边界', async ({ page }) => {
  const mock = await mockApi(page, true)
  await page.goto('environments')
  await page.getByRole('button', { name: '新增环境', exact: true }).click()
  await page.locator('#env-key').fill('new')
  await page.locator('#env-name').fill('新环境')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.goto('resources' + scopeQuery)
  await page.locator('input[type=file]').setInputFiles({ name: 'fixture.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  await expect.poll(() => mock.count('asset/upload')).toBe(1)
  await page.goto('import-export')
  await page.getByRole('tab', { name: '数据导入', exact: true }).click()
  await page.locator('#import-file').setInputFiles({ name: 'fixture.zip', mimeType: 'application/zip', buffer: Buffer.from('mock preview fixture') })
  await expect(page.getByRole('heading', { name: '选择导入内容', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '开始导入', exact: true }).click()
  await expect.poll(() => mock.count('transfer/import-selective')).toBe(1)
  await page.getByRole('tab', { name: '数据导出', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择环境 演示环境', exact: true }).check()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '导出数据', exact: true }).click()])
  expect(download.suggestedFilename()).toMatch(/\.zip$/)
  for (const endpoint of ['environment/create', 'asset/upload', 'transfer/import-preview', 'transfer/import-selective', 'transfer/export']) {
    expect(mock.count(endpoint), endpoint).toBe(1)
    expect(mock.writes(endpoint).every(request => request.headers()['x-csrf-token'] === CSRF && !request.headers()['authorization'])).toBe(true)
  }
  expect(mock.writes('asset/upload')[0].headers()['content-type']).toMatch(/^multipart\/form-data; boundary=/)
  expect(mock.writes('transfer/import-preview')[0].headers()['content-type']).toMatch(/^multipart\/form-data; boundary=/)
  expect(mock.requests.every(request => !new URL(request.url()).pathname.includes('/rainbow-bridge/rainbow-bridge/'))).toBe(true)
})

test('D-F04 冻结和发布不输密钥，结果不确定时原样重发同一payload', async ({ page }) => {
  const mock = await mockApi(page, true)
  await page.goto('config' + scopeQuery)
  await page.getByRole('button', { name: '锁版', exact: true }).click()
  await expect(page.getByRole('dialog').locator('input[type=password]')).toHaveCount(0)
  await page.locator('#freeze-reason').fill('验收冻结')
  await page.getByRole('button', { name: '确认锁定', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.goto('releases' + scopeQuery)
  mock.overrides.set('release/create', route => fail(route, 503, 'RELEASE_STORAGE_BUSY'))
  await page.getByRole('button', { name: '创建版本', exact: true }).click()
  await expect(page.getByRole('dialog').locator('input[type=password]')).toHaveCount(0)
  await page.locator('#release-version').fill('v2')
  await page.locator('#release-reason').fill('创建验收版本')
  await page.getByRole('button', { name: '保存版本', exact: true }).click()
  await page.getByRole('button', { name: '确认结果(同一请求标识)', exact: true }).click()
  await expect.poll(() => mock.count('release/create')).toBe(2)
  expect(mock.writes('release/create')[0].postDataJSON()).toEqual(mock.writes('release/create')[1].postDataJSON())
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  mock.overrides.set('release/activate', route => route.abort('failed'))
  await page.getByRole('button', { name: '切换生效版本', exact: true }).click()
  await expect(page.getByRole('dialog').locator('input[type=password]')).toHaveCount(0)
  await page.locator('#activate-reason').fill('切换验收版本')
  await page.getByRole('dialog').getByRole('button', { name: '切换生效版本', exact: true }).click()
  await page.getByRole('button', { name: '确认结果(同一请求标识)', exact: true }).click()
  await expect.poll(() => mock.count('release/activate')).toBe(2)
  expect(mock.writes('release/activate')[0].postDataJSON()).toEqual(mock.writes('release/activate')[1].postDataJSON())
  for (const endpoint of ['freeze/lock', 'release/create', 'release/activate']) {
    expect(mock.writes(endpoint).every(request => request.headers()['x-csrf-token'] === CSRF && !request.headers()['authorization'])).toBe(true)
  }
})

test('D-F06 写请求401后重新登录不自动重放，403禁用账号不循环恢复', async ({ page }) => {
  const mock = await mockApi(page, true)
  mock.overrides.set('environment/create', route => fail(route, 401, 'AUTH_REQUIRED'))
  await page.goto('environments')
  await page.getByRole('button', { name: '新增环境', exact: true }).click()
  await page.locator('#env-key').fill('new')
  await page.locator('#env-name').fill('新环境')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录工作台', exact: true })).toBeVisible()
  await login(page)
  await expect(page.getByRole('heading', { name: '环境管理', exact: true })).toBeVisible()
  expect(mock.count('environment/create')).toBe(1)
  mock.overrides.set('asset/list', route => fail(route, 403, 'AUTH_FORBIDDEN'))
  await page.goto('resources' + scopeQuery)
  await expect(page.getByRole('heading', { name: '登录工作台', exact: true })).toBeVisible()
  await expect(page.locator('[data-sonner-toast]').filter({ hasText: '账号不可用' })).toHaveCount(1)
  expect(mock.count('auth/me')).toBe(2)
})

test('恢复中的me仅一份；主动刷新503显示恢复状态，重试401安全返回登录', async ({ page }) => {
  const mock = await mockApi(page, true)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  mock.overrides.set('auth/me', async route => { await gate; await ok(route, identity) })
  await page.goto('./')
  await page.getByRole('navigation', { name: '主要导航' }).getByRole('link', { name: '配置管理', exact: true }).click()
  expect(mock.count('auth/me')).toBe(1)
  expect(mock.count('config/list')).toBe(0)
  release()
  await expect(page.getByRole('heading', { name: '配置管理', exact: true })).toBeVisible()
  mock.overrides.set('asset/list', route => fail(route, 403, 'AUTH_CSRF_INVALID'))
  await page.goto('resources' + scopeQuery)
  mock.overrides.set('auth/me', route => fail(route, 503, 'AUTH_UNAVAILABLE'))
  await page.getByRole('button', { name: '刷新会话', exact: true }).click()
  await expect(page.getByRole('heading', { name: '暂时无法确认登录状态', exact: true })).toBeVisible()
  mock.overrides.set('auth/me', route => fail(route, 401, 'AUTH_REQUIRED'))
  await page.getByRole('button', { name: '重试会话恢复', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录工作台', exact: true })).toBeVisible()
})

test('导出401/非归档响应不会伪装下载成功', async ({ page }) => {
  const mock = await mockApi(page, true)
  let downloads = 0
  page.on('download', () => downloads++)
  await page.goto('import-export')
  await page.getByRole('checkbox', { name: '选择环境 演示环境', exact: true }).check()
  mock.overrides.set('transfer/export', route => ok(route, { error: 'not a zip' }))
  await page.getByRole('button', { name: '导出数据', exact: true }).click()
  await expect(page.getByText('导出响应不是有效的归档文件，请重试', { exact: true })).toBeVisible()
  expect(downloads).toBe(0)
  mock.overrides.set('transfer/export', route => fail(route, 401, 'AUTH_REQUIRED'))
  await page.getByRole('button', { name: '导出数据', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录工作台', exact: true })).toBeVisible()
  expect(downloads).toBe(0)
})
